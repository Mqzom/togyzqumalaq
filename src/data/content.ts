export const copy: Record<Lang, Copy> = { kz, ru }

export function playerName(
  lang: Lang,
  id: PlayerId,
  mode: 'pvp' | 'pvc',
  human: PlayerId = 0,
): string {
  const t = copy[lang].game
  if (mode === 'pvc') return id === human ? t.you : t.computer
  return `${t.player} ${id + 1}`
}

export function stoneWord(lang: Lang, count: number): string {
  if (lang === 'kz') return 'құмалақ'
  const mod100 = Math.abs(count) % 100
  const mod10 = mod100 % 10
  if (mod100 > 10 && mod100 < 20) return 'камней'
  if (mod10 === 1) return 'камень'
  if (mod10 >= 2 && mod10 <= 4) return 'камня'
  return 'камней'
}
